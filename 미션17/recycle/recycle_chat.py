GREETING = re.compile(r"^(안녕|하이|헬로|hello|hi\b|반가|ㅎㅇ)", re.IGNORECASE)
THANKS = re.compile(r"(고마|감사|땡큐|thank|ㄱㅅ)", re.IGNORECASE)
HELP = re.compile(r"(뭐 할 수|뭘 할 수|할 수 있어|사용법|도움말|어떻게 써|기능)")
# 품목 검색 전에 질문에서 빼는 표현 (의미 검색 정확도를 높이기 위함)
FILLER = re.compile(
    r"(은|는|이|가|을|를)?\s*(어디에?|어떻게|어케|뭐로|무엇으로)?\s*"
    r"(버려야\s*(돼|해|하나요|되나요|할까요?)?|버려요|버리나요|버리는\s*(법|방법|곳)|버려|분리\s*수거|분리\s*배출|처리\s*(방법|법)?|해야\s*돼)"
    r"|[?？!.~]+"
)


@dataclass
class Answer:
    """채팅 답변: 화면에 표시할 본문과 '생각 과정'에 보여줄 정보."""

    text: str
    thinking: list[str] = field(default_factory=list)  # 생각 과정에 보여줄 줄들
    category: str | None = None  # 기록(통계)에 쓸 분류 이름


class TextMatcher:
    """한국어 질문을 지식 사전의 품목과 연결합니다.

    [허브 벌점] 문장 임베딩에서는 일부 단어(예: '지퍼백', '코인전지')의 벡터가 거의 모든 문장과
    비슷하게 나오는 '허브(hub) 현상'이 있습니다. 그대로 쓰면 "오늘 날씨 어때?"도 지퍼백으로 답해 버립니다.
    그래서 각 품목 이름이 '분리수거와 상관없는 일상 문장들'과 평균적으로 얼마나 비슷한지(허브 정도)를
    미리 계산해 두고, 검색 점수에서 빼 줍니다.  (단어 번역 연구의 CSLS 기법과 같은 아이디어)
        점수 = cos(질문, 품목 이름) - 평균 cos(품목 이름, 일상 문장들)
    """

    def __init__(self) -> None:
        download_models()
        self.session = ort.InferenceSession(str(model_path("ko_text")), providers=["CPUExecutionProvider"])
        self.tokenizer = Tokenizer.from_file(str(model_path("ko_tokenizer")))
        self.tokenizer.enable_truncation(max_length=64)

        # 품목 이름 + 별칭을 모두 검색 대상으로 사용 (별칭 하나하나가 품목을 가리킴)
        self.names: list[str] = []
        self.owner: list[int] = []
        for i, item in enumerate(KB):
            for name in (item.name, *item.aliases):
                self.names.append(name)
                self.owner.append(i)
        self.name_embeds = np.stack([self.embed(n) for n in self.names])
        ref = np.stack([self.embed(s) for s in REFERENCE_SENTENCES])
        self.hub_penalty = (self.name_embeds @ ref.T).mean(axis=1)  # 품목 이름별 허브 정도

    def embed(self, text: str) -> np.ndarray:
        """문장을 384차원 벡터로 바꿉니다 (토큰 벡터의 평균 = mean pooling, 길이 1로 정규화)."""
        enc = self.tokenizer.encode(text)
        ids = np.array([enc.ids], dtype=np.int64)
        mask = np.array([enc.attention_mask], dtype=np.int64)
        hidden = self.session.run(None, {"input_ids": ids, "attention_mask": mask,
                                         "token_type_ids": np.zeros_like(ids)})[0]
        vec = (hidden * mask[..., None]).sum(axis=1)[0] / mask.sum()
        return vec / np.linalg.norm(vec)

    def find_exact(self, query: str) -> int | None:
        """질문 안에 품목 이름/별칭이 그대로 들어 있으면 그 품목 번호를 반환합니다.

        여러 개가 들어 있으면 질문 앞쪽에 나온 것(주어)을, 같은 위치면 더 긴 이름을 고릅니다.
        예) "치킨 뼈는 음식물 쓰레기야?" -> '치킨뼈'(앞쪽)를 선택, '음식물'은 무시
        """
        q = query.replace(" ", "").lower()
        hits = []
        for i, n in enumerate(self.names):
            key = n.replace(" ", "").lower()
            pos = q.find(key)
            if len(key) >= 2 and pos >= 0:  # 한 글자 별칭은 오탐이 많아서 제외
                hits.append((-pos, len(key), self.owner[i]))
        return max(hits)[2] if hits else None

    def search(self, query: str, k: int = 3) -> list[tuple[int, float]]:
        """의미가 가장 비슷한 품목 k개를 (품목 번호, 점수)로 반환합니다."""
        core = FILLER.sub(" ", query).strip() or query
        sims = self.name_embeds @ self.embed(core) - self.hub_penalty
        best: dict[int, float] = {}
        for idx in sims.argsort()[::-1]:
            item = self.owner[idx]
            if item not in best:
                best[item] = float(sims[idx])
            if len(best) == k:
                break
        return list(best.items())

    # --- 글 질문에 답하기 ------------------------------------------------------
    def answer(self, query: str) -> Answer:
        q = query.strip()
        if GREETING.search(q):
            return Answer(random.choice([
                "안녕하세요! 저는 분리수거 도우미예요. :material/recycling:\n\n",
                "반가워요! 오늘은 어떤 쓰레기가 고민이세요? :material/recycling:\n\n",
            ]) + USAGE, ["인사말이라서 바로 대답했어요."])
        if THANKS.search(q) and len(q) < 20:
            return Answer("천만에요! 분리수거 잘하는 당신, 지구가 고마워할 거예요. :material/eco:\n\n"
                          "또 헷갈리는 게 있으면 언제든 물어보세요.", ["감사 인사라서 바로 대답했어요."])
        if HELP.search(q):
            return Answer(USAGE, ["사용법 질문이라서 도움말을 보여드려요."])

        exact = self.find_exact(q)
        if exact is not None:
            item = KB[exact]
            return Answer(item_answer(item), [f"질문에서 품목 이름 **'{item.name}'**{josa(item.name, '을', '를')} 찾았어요 (사전 일치)."],
                          item.category)

        top = self.search(q)
        thinking = ["질문에 정확히 일치하는 품목 이름이 없어서, 문장 임베딩으로 의미가 비슷한 품목을 찾았어요."]
        thinking += [f"{KB[i].name} — 점수 {s:.2f}" for i, s in top]
        best, sim = top[0]
        if sim >= SIM_CONFIDENT:
            return Answer(item_answer(KB[best]), thinking, KB[best].category)
        if sim >= SIM_MAYBE:
            cands = [f"**{KB[i].name}**" for i, s in top if s >= SIM_MAYBE]  # 점수가 너무 낮은 후보는 제외
            ask = f"혹시 {cands[0]}인가요?" if len(cands) == 1 else f"혹시 {', '.join(cands)} 중 하나인가요?"
            return Answer(f"음, 정확히 어떤 물건인지 잘 모르겠어요. {ask}\n\n"
                          "물건 이름을 조금 더 구체적으로 알려주시거나, + 버튼으로 사진을 보여주세요!", thinking)
        return Answer("죄송해요, 그건 제가 잘 모르는 내용이에요. :material/sentiment_dissatisfied:\n\n"
                      "저는 **쓰레기를 어디에 어떻게 버리는지** 알려드릴 수 있어요. "
                      "예를 들어 *\"우유팩 어떻게 버려?\"* 처럼 물어봐 주세요.", thinking)


USAGE = (
    "이렇게 물어볼 수 있어요.\n\n"
    "- **글로 질문**: *\"치킨 뼈는 음식물 쓰레기야?\"*, *\"아이스팩 어떻게 버려?\"*\n"
    "- **사진으로 질문**: 입력창 왼쪽 **+** 버튼으로 쓰레기 사진을 올려 주세요."
)


# ---------------------------------------------------------------------------
# 답변 문장 만들기
# ---------------------------------------------------------------------------
def josa(word: str, with_final: str, without_final: str) -> str:
    """단어의 마지막 글자 받침에 맞는 조사를 고릅니다. 예) josa("치킨 뼈", "은", "는") -> "는"

    '(으)로'는 받침이 없거나 받침이 ㄹ이면 '로'를 씁니다 (예: 종이로, 고철로).
    """
    last = word.rstrip()[-1:]
    if not ("가" <= last <= "힣"):
        return without_final
    final = (ord(last) - ord("가")) % 28  # 0 = 받침 없음, 8 = ㄹ
    if with_final == "으로" and final == 8:
        return without_final
    return with_final if final else without_final


def item_answer(item: Item) -> str:
    """지식 사전 품목에 대한 대화체 답변."""
    cat = item.cat
    opener = random.choice(["", "좋은 질문이에요! ", "헷갈리기 쉬운 거죠. "])
    topic = f"**{item.name}**{josa(item.name, '은', '는')}"
    if item.bin:  # 형광등, 약, 헌 옷처럼 전용 수거함이 따로 있는 품목
        head = f"{opener}{topic} **{item.bin}**에 버려요."
    else:
        head = f"{opener}{topic} **{cat.icon} {cat.name}**{josa(cat.name, '으로', '로')} 분류돼요."
    lines = [head, "", f"**버리는 곳:** {item.bin or cat.bin}", ""]
    lines += [f"- {t}" for t in (item.tips or cat.how)]
    return "\n".join(lines)


def image_answer(result: dict, low_confidence: float = 0.5) -> Answer:
    """CLIP 사진 분류 결과에 대한 대화체 답변."""
    probs, best = result["probs"], result["best"]
    order = probs.argsort()[::-1]
    cat, conf = CATEGORIES[best], float(probs[best])
    thinking = ["CLIP 모델로 사진과 38개 설명 문장을 비교했어요."]
    thinking += [f"{CATEGORIES[i].name} — {probs[i]:.0%}" for i in order[:3]]

    lines = [f"사진을 보니 **{result['item']}** 같아요! **{cat.icon} {cat.name}**{josa(cat.name, '으로', '로')} "
             f"버리면 돼요. (확신도 {conf:.0%})", "",
             f"**버리는 곳:** {cat.bin}", ""]
    lines += [f"- {t}" for t in cat.how]
    if conf < low_confidence:
        alt = CATEGORIES[int(order[1])]
        lines += ["", f"그런데 확신이 크지 않아요. **{alt.icon} {alt.name}**일 수도 있어요 ({probs[order[1]]:.0%}). "
                      "물건만 크게 나오게 다시 찍거나, 물건 이름을 글로 알려주시면 더 정확하게 알려드릴게요."]
    return Answer("\n".join(lines), thinking, cat.name)
